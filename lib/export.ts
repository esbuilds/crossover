// "Download brief": the brief as a markdown file, plus the outreach draft once approved. No imports, runs in the
// browser. The brief text already carries the scorecard numbers, the launch market, and the venues.
export type ExportInput = { seed: string; partner: string; basedOn?: string[]; brief: string; outreach?: string; date: string };

export function briefMarkdown({ seed, partner, basedOn, brief, outreach, date }: ExportInput) {
  return [
    `# ${seed} x ${partner}: partnership brief`,
    "",
    `Generated by Crossover from Qloo taste data on ${date}.${basedOn?.length ? ` ${seed} isn't in Qloo yet; this is based on fans of ${basedOn.join(", ")}.` : ""}`,
    "",
    brief.trim(),
    ...(outreach?.trim() ? ["", "## Outreach draft", "", outreach.trim()] : []),
    "",
  ].join("\n");
}

export const exportFilename = (seed: string, partner: string) =>
  `${seed}-x-${partner}-brief.md`
    .toLowerCase()
    .replace(/[^a-z0-9.-]+/g, "-")
    .replace(/-+/g, "-");
